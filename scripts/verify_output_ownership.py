#!/usr/bin/env python3
"""Exercise configured output provenance and fail-closed publication recovery."""

import argparse
from base64 import b64encode
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile


SHARD = "BlueprintMocks.generated.swift"
INDEX = "BlueprintMockingIndex.generated.swift"
JOURNAL = ".blueprint-mocking-transaction.json"
CHECKPOINT = "BLUEPRINT_TEST_PUBLICATION_CHECKPOINT"
HEADER = b"// Generated by Blueprint Mocking. Do not edit.\n"
USER_SWIFT = b"public enum IndependentlyAuthored {}\n"
DIRTY = b'#error("Blueprint Mocking: interrupted output publication. Rerun generation to recover.")\n'


def digest(contents):
    return hashlib.sha256(contents).hexdigest()


def snapshot(directory):
    return directory.stat().st_mtime_ns, {
        path.name: (path.read_bytes(), path.stat().st_mtime_ns)
        for path in sorted(directory.iterdir())
    }


def verify(tool, fault_tool, evidence):
    checks = {}
    environment = os.environ.copy()
    environment.pop(CHECKPOINT, None)
    with tempfile.TemporaryDirectory(prefix="Configured Output Ownership ", dir=evidence) as work:
        root = Path(work)
        config, source = root / "blueprint-mocking.json", root / "Lookup.swift"
        config.write_text(json.dumps({"schemaVersion": 1, "selections": [
            {"module": "Domain", "type": "Lookup", "kind": "protocol"}
        ]}) + "\n", encoding="utf-8")
        source.write_text("public protocol Lookup: Sendable { func find(_ key: String) -> String }\n",
                          encoding="utf-8")
        authored = snapshot(root)[1]

        def run(label, output, *, verb="generate", status=0, diagnostic=None, interrupt=False):
            args = [str(fault_tool if interrupt else tool), verb, "--config", str(config),
                    "--output", str(output), "--input-set-id", "176", "--source", "Domain", str(source)]
            env = environment | ({CHECKPOINT: "after-shard"} if interrupt else {})
            result = subprocess.run(args, cwd=root, env=env, stdin=subprocess.DEVNULL,
                                    capture_output=True, timeout=30, check=False)
            record = {"exit": result.returncode}
            for stream in ("stdout", "stderr"):
                payload = getattr(result, stream)
                log = f"ownership-{label}.{stream}.log"
                (evidence / log).write_bytes(payload)
                record[stream] = {"log": log, "sha256": digest(payload)}
            checks[label] = record
            if result.returncode != status:
                raise ValueError(f"{label}: expected CLI exit {status}, got {result.returncode}. See ownership logs.")
            if diagnostic is not None and diagnostic not in result.stderr:
                raise ValueError(f"{label}: expected {diagnostic!r}, got {result.stderr!r}")
            if status != 0 and result.stdout:
                raise ValueError(f"{label}: rejected generation reported output on stdout")
            if any((root / name).read_bytes() != data or (root / name).stat().st_mtime_ns != mtime
                   for name, (data, mtime) in authored.items()):
                raise ValueError(f"{label}: CLI changed authored source/configuration")
            print(f"PASS: configured output ownership {label}", flush=True)

        def reject_unchanged(label, output, diagnostic, *, verb="generate", status=1):
            previous = snapshot(output)
            run(label, output, verb=verb, status=status, diagnostic=diagnostic)
            if snapshot(output) != previous:
                raise ValueError(f"{label}: failed request changed output bytes, timestamps, or file set")

        def collision(output_name):
            return f"error: BPM004: Refusing to overwrite unowned generated output: {output_name}".encode()

        for name in (SHARD, INDEX):
            output = root / ("User Owns " + name)
            output.mkdir()
            (output / name).write_bytes(USER_SWIFT)
            reject_unchanged("collision-" + name, output, collision(name))

        output = root / "Owned Pair"
        run("publish", output)
        shard, index = output / SHARD, output / INDEX
        exact = {path.name: path.read_bytes() for path in (shard, index)}
        if not all(data.startswith(HEADER) for data in exact.values()):
            raise ValueError("Baseline generated files did not carry existing provenance")
        notes = output / "Unrelated.swift"
        notes.write_bytes(USER_SWIFT)
        baseline = snapshot(output)
        run("repeat-with-unrelated-file", output)
        if snapshot(output) != baseline:
            raise ValueError("An unchanged publish rewrote generated or unrelated files")

        shard.write_bytes(exact[SHARD] + b"// Drift by a test author.\n")
        reject_unchanged("reported-owned-drift", output, b"error: BPM003: Generated files differ",
                         verb="verify-generated", status=3)
        run("repair-owned-drift", output)
        after_repair = snapshot(output)[1]
        # Repair uses the canonical transaction, which marks the index dirty
        # before restoring its exact final bytes even when only the shard drifted.
        if (any(after_repair[name][0] != data for name, data in exact.items())
                or after_repair[notes.name] != baseline[1][notes.name]):
            raise ValueError("Drift repair missed canonical bytes or changed an unrelated file")

        shard.write_bytes(exact[SHARD].replace(b"\n", b"\r\n"))
        run("repair-owned-crlf-drift", output)
        after_repair = snapshot(output)[1]
        if any(after_repair[name][0] != data for name, data in exact.items()):
            raise ValueError("CRLF drift repair did not restore canonical bytes")

        index.unlink()
        run("repair-missing-owned-index", output)
        if index.read_bytes() != exact[INDEX] or snapshot(output)[1][SHARD] != after_repair[SHARD]:
            raise ValueError("Repairing a missing index rewrote the unchanged shard")

        shard.write_bytes(USER_SWIFT)
        reject_unchanged("human-owned-file-beside-valid-generated-index", output, collision(SHARD))
        shard.write_bytes(exact[SHARD])
        index.write_bytes(DIRTY)
        reject_unchanged("dirty-marker-without-recovery-record", output, collision(INDEX))
        index.write_bytes(exact[INDEX])

        journal = output / JOURNAL
        journal.write_bytes(b"{bad JSON\n")
        reject_unchanged("invalid-recovery-json", output, b"error: BPM004: Invalid generated output recovery journal")
        journal.unlink()

        pending = root / "Interrupted Pair"
        run("interrupt-first-generation-after-shard", pending, status=93, interrupt=True,
            diagnostic=b"DX013 fixture: interrupted at after-shard")
        shard, index, journal = (pending / name for name in (SHARD, INDEX, JOURNAL))
        staged = {path.name: path.read_bytes() for path in (shard, index, journal)}
        if staged[INDEX] != DIRTY or staged[SHARD] != exact[SHARD]:
            raise ValueError("The actual CLI interruption did not publish the dirty checkpoint")

        for path in (shard, index):
            path.write_bytes(USER_SWIFT)
            reject_unchanged("unrelated-current-" + path.name, pending,
                             b"error: BPM004: Current generated outputs do not match the recovery journal")
            path.write_bytes(staged[path.name])

        record = json.loads(staged[JOURNAL])
        # Shape-valid, including our real generated next pair. A bad record could
        # otherwise authorize recovery over whatever matches its previous payload.
        record["previous"] = {"index": b64encode(USER_SWIFT).decode("ascii")}
        journal.write_text(json.dumps(record) + "\n", encoding="utf-8")
        reject_unchanged("unowned-recovery-payload", pending,
                         b"error: BPM004: Invalid generated output recovery journal")
        journal.write_bytes(staged[JOURNAL])

        run("retry-real-interruption", pending)
        recovered = snapshot(pending)
        if set(recovered[1]) != {SHARD, INDEX} or any(
            recovered[1][name][0] != contents for name, contents in exact.items()
        ):
            raise ValueError("The trusted checkpoint did not recover the exact canonical pair")
        run("verify-recovered-pair", pending, verb="verify-generated")
        run("repeat-after-recovery", pending)
        if snapshot(pending) != recovered:
            raise ValueError("Post-recovery no-op rewrote generated files or metadata")
    return checks


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tool", required=True, type=Path)
    parser.add_argument("--fault-tool", required=True, type=Path)
    parser.add_argument("--evidence-dir", required=True, type=Path)
    options = parser.parse_args()
    try:
        evidence = options.evidence_dir.resolve()
        evidence.mkdir(parents=True, exist_ok=True)
        report = evidence / "output-ownership-report.json"
        report.unlink(missing_ok=True)
        tool, fault_tool = (path.resolve(strict=True) for path in (options.tool, options.fault_tool))
        if tool == fault_tool:
            raise ValueError("Supply distinct normal and fault-instrumented generator builds")
        checks = verify(tool, fault_tool, evidence)
        report.write_text(json.dumps({"checks": checks}, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        parser.exit(1, f"{error}\n")
    print(f"EVIDENCE: {report.name} SHA-256 {digest(report.read_bytes())}")
    print("PASS: DX011 configured provenance collisions and legitimate recovery")


if __name__ == "__main__":
    main()
