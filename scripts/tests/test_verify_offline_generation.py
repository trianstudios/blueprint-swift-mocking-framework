from pathlib import Path
import sys
import tempfile
import unittest


sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from verify_offline_generation import validate_generated_outputs, validate_parser_trace


PARSER = "libSwiftParser.dylib"
SYNTAX = "libSwiftSyntax.dylib"
UUID = "F5AE5C3A-9B76-3CDE-A181-4E3FA310D981"
SHARD = "BlueprintMocks.generated.swift"
INDEX = "BlueprintMockingIndex.generated.swift"
SHARD_MARKER = b"BlueprintMockingShard_0ab19c"
INPUT_SET = b"// SwiftPM input set: 91\n"
OUTPUTS = {
    SHARD: b"// Generated by Blueprint Mocking. Do not edit.\nenum "
    + SHARD_MARKER + b" {}\n",
    INDEX: b"// Generated by Blueprint Mocking. Do not edit.\n" + INPUT_SET
    + b"enum BlueprintMockingGeneratedIndex { typealias Shard = " + SHARD_MARKER + b" }\n",
}


def loaded_image(path, uuid=UUID):
    return f"dyld[4102]: <{uuid}> {path}\n".encode()


class ParserTraceTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="Offline Parser Trace ")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name).resolve()
        approved = self.root / "Xcode With Spaces" / "lib" / "swift" / "host"
        approved.mkdir(parents=True)
        self.expected = {name: approved / name for name in (PARSER, SYNTAX)}
        for path in self.expected.values():
            path.touch()
        self.parser = loaded_image(self.expected[PARSER])
        self.syntax = loaded_image(self.expected[SYNTAX])

    def test_accepts_approved_dyld_image_paths_with_spaces_and_unrelated_images(self):
        unrelated = loaded_image("/usr/lib/libSystem.B.dylib")
        validate_parser_trace(unrelated + self.syntax + self.parser, self.expected)

    def test_requires_both_parser_and_syntax_records(self):
        for trace in (b"", self.parser, self.syntax):
            with self.subTest(trace=trace), self.assertRaises(ValueError):
                validate_parser_trace(trace, self.expected)

    def test_rejects_plain_text_and_incomplete_dyld_lines_as_parser_records(self):
        path = self.expected[PARSER]
        for counterfeit in (
            f"preflight: <{UUID}> {path}\n".encode(),
            b"embedded trace: " + self.parser,
            f"dyld[4102]: {path}\n".encode(),
            loaded_image(path, "not-an-image-uuid"),
            loaded_image(Path("Xcode With Spaces/lib/swift/host") / PARSER),
        ):
            with self.subTest(trace=counterfeit), self.assertRaises(ValueError):
                validate_parser_trace(counterfeit + self.syntax, self.expected)

    def test_rejects_foreign_approved_basename_even_alongside_approved_record(self):
        foreign = self.root / "Different Toolchain" / PARSER
        foreign.parent.mkdir()
        foreign.touch()
        for trace in (loaded_image(foreign) + self.syntax, self.parser + self.syntax + loaded_image(foreign)):
            with self.subTest(trace=trace), self.assertRaises(ValueError):
                validate_parser_trace(trace, self.expected)

    def test_rejects_duplicate_image_records_for_same_approved_path(self):
        for trace in (self.parser + self.syntax + self.parser, self.parser + self.syntax + self.syntax):
            with self.subTest(trace=trace), self.assertRaises(ValueError):
                validate_parser_trace(trace, self.expected)


class GeneratedOutputsTests(unittest.TestCase):
    def test_accepts_exact_generated_shard_and_matching_index(self):
        validate_generated_outputs(OUTPUTS, dict(reversed(tuple(OUTPUTS.items()))))

    def test_rejects_missing_unknown_or_empty_outputs_in_either_lane(self):
        for invalid in (
            {SHARD: OUTPUTS[SHARD]},
            {INDEX: OUTPUTS[INDEX]},
            OUTPUTS | {"Unexpected.generated.swift": b"// unexpected\n"},
            OUTPUTS | {SHARD: b""},
            OUTPUTS | {INDEX: b""},
        ):
            with self.subTest(outputs=invalid):
                with self.assertRaises(ValueError):
                    validate_generated_outputs(OUTPUTS, invalid)
                with self.assertRaises(ValueError):
                    validate_generated_outputs(invalid, OUTPUTS)
                with self.assertRaises(ValueError):
                    validate_generated_outputs(invalid, invalid)

    def test_rejects_changed_raw_bytes_in_each_output(self):
        for name in (SHARD, INDEX):
            with self.subTest(name=name), self.assertRaises(ValueError):
                validate_generated_outputs(OUTPUTS, OUTPUTS | {name: OUTPUTS[name] + b"\n"})

    def test_rejects_comment_lookalikes_and_duplicate_shard_markers(self):
        shard = OUTPUTS[SHARD]
        for invalid in (
            shard.replace(b"enum " + SHARD_MARKER, b"// enum " + SHARD_MARKER),
            shard + b"enum BlueprintMockingShard_a1 {}\n",
        ):
            with self.subTest(shard=invalid), self.assertRaises(ValueError):
                altered = OUTPUTS | {SHARD: invalid}
                validate_generated_outputs(altered, altered)

    def test_requires_lowercase_hex_even_when_shard_and_index_match(self):
        altered = {
            name: content.replace(SHARD_MARKER, b"BlueprintMockingShard_0AB19C")
            for name, content in OUTPUTS.items()
        }
        with self.assertRaises(ValueError):
            validate_generated_outputs(altered, altered)

    def test_rejects_index_alias_substrings_comments_and_wrong_input_set(self):
        index = OUTPUTS[INDEX]
        for invalid in (
            index.replace(SHARD_MARKER, SHARD_MARKER + b"2"),
            index.replace(b"enum BlueprintMockingGeneratedIndex", b"// enum BlueprintMockingGeneratedIndex"),
            index.replace(INPUT_SET, b"// SwiftPM input set: 910\n"),
            index.replace(INPUT_SET, b""),
        ):
            with self.subTest(index=invalid), self.assertRaises(ValueError):
                altered = OUTPUTS | {INDEX: invalid}
                validate_generated_outputs(altered, altered)
