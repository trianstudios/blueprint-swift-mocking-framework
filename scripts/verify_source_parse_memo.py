#!/usr/bin/env python3
"""Check invocation-local parsing without bypassing a current source read."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import selectors
import subprocess
import tempfile

from verify_generation_contention import PausedWriter, pause_event
from verify_generation_recovery import CHECKPOINT_FLAG, GENERATED, INDEX, SHARD

TRACE = "BLUEPRINT_TEST_OBSERVE_SOURCE_PARSE"
PAUSE = "BLUEPRINT_TEST_PUBLICATION_PAUSE_AT"
BEFORE = b"public protocol Lookup: Sendable { func value() -> Int  }\n"
AFTER = b"public protocol Lookup: Sendable { func value() -> Bool }\n"


def digest(payload):
    return hashlib.sha256(payload).hexdigest()


def verify(tool, fault, evidence):
    checks = {}
    environment = os.environ.copy()
    for flag in (TRACE, PAUSE, CHECKPOINT_FLAG, "BLUEPRINT_TEST_OBSERVE_OUTPUT_LOCK"):
        environment.pop(flag, None)

    with tempfile.TemporaryDirectory(prefix="Invocation Parse Memo ", dir=evidence) as temporary:
        root = Path(temporary)
        config = root / "blueprint-mocking.json"
        config.write_text(json.dumps({"schemaVersion": 1, "selections": [
            {"module": "Domain", "type": "Lookup", "kind": "protocol"}
        ]}) + "\n", encoding="utf-8")
        source = root / "Lookup.swift"
        source.write_bytes(BEFORE)
        identical = [root / name for name in ("Left Support.swift", "Right Support.swift")]
        for path in identical:
            path.write_text("struct SupplementalDeclaration {}\n", encoding="utf-8")

        def parse_event(path):
            return f"DX012 fixture: parse Domain {path}\n".encode()

        def command(executable, output, files):
            args = [executable, "generate", "--config", config, "--output", output, "--input-set-id", "181"]
            for file in files:
                args.extend(["--source", "Domain", file])
            return args

        def record(label, result):
            status, stdout, stderr = result
            artifacts = {}
            for name, data in (("stdout", stdout), ("stderr", stderr)):
                log = evidence / f"parse-memo-{label}.{name}.log"
                log.write_bytes(data)
                artifacts[name] = {"log": log.name, "sha256": digest(data)}
            checks[label] = {"exit": status, "logs": artifacts,
                             "observedParses": stderr.count(b"DX012 fixture: parse ")}

        def require_success(label, result, events=b""):
            record(label, result)
            status, stdout, stderr = result
            if (status, stdout, stderr) != (0, GENERATED, events):
                raise ValueError(f"{label}: expected {events.count(b'DX012 fixture: parse ')} parses, "
                                 f"saw {checks[label]['observedParses']} with status {status}. See parse-memo logs.")
            print(f"PASS: invocation-local source parse memo {label}", flush=True)

        def run(executable, output, files, *, extra=None):
            result = subprocess.run(command(executable, output, files), cwd=root,
                                    env=environment | (extra or {}), stdin=subprocess.DEVNULL,
                                    capture_output=True, timeout=30, check=False)
            return result.returncode, result.stdout, result.stderr

        def pair(output):
            return {name: (output / name).read_bytes() for name in (SHARD, INDEX)}

        files = [source, *identical]
        stable = root / "First Configured Output"
        expected_events = b"".join(parse_event(path) for path in sorted(files))
        require_success("unchanged-first-publication", run(fault, stable, files, extra={TRACE: "1"}),
                        expected_events)
        baseline = root / "Uninstrumented Control"
        require_success("uninstrumented-control", run(tool, baseline, files, extra={
            TRACE: "1", PAUSE: "after-preflight",
        }))
        if pair(baseline) != pair(stable):
            raise ValueError("Invocation-local syntax memo changed generated bytes")
        previous = {name: (stable / name).stat().st_mtime_ns for name in (SHARD, INDEX)}
        require_success("steady-output-rebuild", run(fault, stable, files, extra={TRACE: "1"}), expected_events)
        if previous != {name: (stable / name).stat().st_mtime_ns for name in (SHARD, INDEX)}:
            raise ValueError("Steady generation rewrote the unchanged pair")

        changed = root / "Changed Before Publication"
        raw_stdout = evidence / "parse-memo-changed-process.stdout"
        with raw_stdout.open("wb") as output, selectors.DefaultSelector() as reader:
            child = subprocess.Popen(command(fault, changed, [source]), cwd=root,
                                     env=environment | {TRACE: "1", PAUSE: "after-preflight"},
                                     stdin=subprocess.PIPE, stdout=output, stderr=subprocess.PIPE, bufsize=0)
            writer = PausedWriter(child, reader, raw_stdout)
            try:
                writer.expect_event(parse_event(source))
                writer.expect_event(pause_event("after-preflight"))
                writer.require_waiting()
                if changed.exists():
                    raise ValueError("Output was created before the preflight boundary")
                old = source.stat()
                source.write_bytes(AFTER)
                os.utime(source, ns=(old.st_atime_ns, old.st_mtime_ns))
                now = source.stat()
                if (BEFORE == AFTER or source.read_bytes() != AFTER or
                        (now.st_size, now.st_mtime_ns) != (old.st_size, old.st_mtime_ns)):
                    raise ValueError("The mutation did not preserve source size and mtime")
                writer.resume()
                changed_result = writer.finish()
            finally:
                if child.poll() is None:
                    child.kill()
                    child.wait(timeout=15)
                child.stdin.close()
                child.stderr.close()
        require_success("same-size-mtime-mutation", changed_result,
                        parse_event(source) + pause_event("after-preflight") + parse_event(source))
        current = root / "Fresh Mutation Control"
        require_success("fresh-mutation-control", run(tool, current, [source]))
        if pair(changed) != pair(current) or b"public func value() -> Bool" not in pair(changed)[SHARD]:
            raise ValueError("Mutated source did not publish the new canonical Bool witness")

        # Preserve the original authored path spelling and Foundation's existing
        # open behavior. Lexically standardizing a symlink/.. path before opening
        # may select a different file when path resolution follows the link.
        authored, physical = root / "Authored", root / "Physical"
        authored.mkdir()
        (physical / "Child").mkdir(parents=True)
        (authored / "Hop").symlink_to(physical / "Child", target_is_directory=True)
        (authored / "Lookup.swift").write_bytes(BEFORE)
        (physical / "Lookup.swift").write_bytes(AFTER)
        spelling = authored / "Hop" / ".." / "Lookup.swift"
        alias_output, alias_baseline = root / "Authored Spelling", root / "Authored Spelling Control"
        require_success("authored-path-spelling", run(fault, alias_output, [spelling], extra={TRACE: "1"}),
                        parse_event(spelling))
        require_success("authored-path-spelling-control", run(tool, alias_baseline, [spelling]))
        if pair(alias_output) != pair(alias_baseline):
            raise ValueError("The memo changed the output for the authored path spelling")

    return checks


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tool", required=True, type=Path)
    parser.add_argument("--fault-tool", required=True, type=Path)
    parser.add_argument("--evidence-dir", required=True, type=Path)
    options = parser.parse_args()
    try:
        evidence = options.evidence_dir.resolve()
        evidence.mkdir(parents=True, exist_ok=True)
        report = evidence / "source-parse-memo-report.json"
        report.unlink(missing_ok=True)
        tool = options.tool.resolve(strict=True)
        fault = options.fault_tool.resolve(strict=True)
        if tool == fault:
            raise ValueError("Use distinct production and instrumented generator executables")
        body = (json.dumps({"checks": verify(tool, fault, evidence)}, sort_keys=True, indent=2) + "\n").encode()
        report.write_bytes(body)
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        parser.exit(1, f"{error}\n")
    print(f"EVIDENCE: {report.name} SHA-256 {digest(body)}")
    print("PASS: DX012 configured first publication reuses only identical authored source parses")


if __name__ == "__main__":
    main()
